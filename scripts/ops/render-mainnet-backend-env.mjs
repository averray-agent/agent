const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/u;
const ACCOUNT_ID32_RE = /^0x[0-9a-fA-F]{64}$/u;
const SCHEMA_RE = /^[a-z_][a-z0-9_]{0,62}$/u;

function requireAddress(value, label) {
  if (typeof value !== "string" || !ADDRESS_RE.test(value)) {
    throw new Error(`deployments/mainnet.json: ${label} must be a 20-byte EVM address`);
  }
  return value;
}

function requireAccountId32(value, label) {
  if (typeof value !== "string" || !ACCOUNT_ID32_RE.test(value)) {
    throw new Error(`deployments/mainnet.json: ${label} must be a 32-byte AccountId`);
  }
  return value.toLowerCase();
}

function wrapperAssetHubImage(wrapperAddress) {
  return `0x${wrapperAddress.slice(2).toLowerCase()}${"ee".repeat(12)}`;
}

/** Fail closed on every current or historical AccountId32-shaped manifest field. */
export function validateManifestAccountId32Fields(value, path = "deployments/mainnet.json") {
  if (Array.isArray(value)) {
    value.forEach((entry, index) => validateManifestAccountId32Fields(entry, `${path}[${index}]`));
    return;
  }
  if (value === null || typeof value !== "object") return;
  for (const [key, entry] of Object.entries(value)) {
    const entryPath = `${path}.${key}`;
    if (/accountId32$/iu.test(key)) {
      requireAccountId32(entry, entryPath.replace(/^deployments\/mainnet\.json\./u, ""));
    } else {
      validateManifestAccountId32Fields(entry, entryPath);
    }
  }
}

function requireBlock(value, label) {
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`deployments/mainnet.json: ${label} must be a positive integer block number`);
  }
  return String(value);
}

function requireWalletList(value, label) {
  if (!Array.isArray(value) || value.length === 0) {
    throw new Error(`deployments/mainnet.json: ${label} must be a non-empty wallet list`);
  }
  return value.map((address, index) => requireAddress(address, `${label}[${index}]`)).join(",");
}

/**
 * The env identifies which wrapper the backend is configured to use. This
 * candidate list deliberately carries no armed/paused verdict: the observer
 * must read dispatchPaused() from every recorded generation at runtime.
 */
export function buildBankWrapperCandidates(manifest, configuredWrapper) {
  const history = manifest.bankXcmDeploymentHistory;
  if (!Array.isArray(history) || history.length === 0) {
    throw new Error("deployments/mainnet.json: bankXcmDeploymentHistory must be a non-empty append-only wrapper history");
  }
  const seen = new Set();
  const candidates = history.map((entry, index) => {
    const version = String(entry?.version ?? "").trim();
    if (!version) {
      throw new Error(`deployments/mainnet.json: bankXcmDeploymentHistory[${index}].version is required`);
    }
    const wrapper = requireAddress(entry?.wrapper, `bankXcmDeploymentHistory[${index}].wrapper`);
    const key = wrapper.toLowerCase();
    if (seen.has(key)) {
      throw new Error(`deployments/mainnet.json: duplicate wrapper ${wrapper} in bankXcmDeploymentHistory`);
    }
    seen.add(key);
    return { version, wrapper };
  });
  if (!seen.has(configuredWrapper.toLowerCase())) {
    throw new Error("deployments/mainnet.json: contracts.xcmWrapper must be present in bankXcmDeploymentHistory");
  }
  return candidates;
}

